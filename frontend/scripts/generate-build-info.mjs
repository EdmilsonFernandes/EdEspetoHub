import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const projectRoot = resolve(process.cwd());
const packageJsonPath = resolve(projectRoot, 'package.json');
const outputPath = resolve(projectRoot, 'src/generated/buildInfo.ts');

const resolveGithubRepoUrl = () => {
  const raw =
    String(process.env.BUILD_GIT_REMOTE_URL || '').trim() ||
    safeExecFile('git', ['remote', 'get-url', 'origin']);
  if (!raw) return '';
  if (raw.startsWith('git@github.com:')) {
    return `https://github.com/${raw.replace('git@github.com:', '').replace(/\.git$/i, '')}`;
  }
  if (raw.startsWith('https://github.com/')) {
    return raw.replace(/\.git$/i, '');
  }
  return '';
};

const safeExecFile = (bin, args) => {
  try {
    return execFileSync(bin, args, { cwd: projectRoot, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  } catch {
    return '';
  }
};

const readExistingBuildInfo = () => {
  try {
    const raw = readFileSync(outputPath, 'utf8');
    const match = raw.match(/export const APP_BUILD_INFO = (\{[\s\S]*\}) as const;/);
    if (!match?.[1]) return null;
    return JSON.parse(match[1]);
  } catch {
    return null;
  }
};

const parseEnvCommits = () => {
  const raw = String(process.env.BUILD_COMMITS_JSON || '').trim();
  if (!raw) return null;
  try {
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed)) return null;
    return parsed;
  } catch {
    return null;
  }
};

const pkg = JSON.parse(readFileSync(packageJsonPath, 'utf8'));
const existing = readExistingBuildInfo();
const commitHash =
  String(process.env.BUILD_GIT_SHA || '').trim() ||
  safeExecFile('git', ['rev-parse', 'HEAD']) ||
  String(existing?.commitHash || '');
const shortHash =
  String(process.env.BUILD_GIT_SHORT_SHA || '').trim() ||
  safeExecFile('git', ['rev-parse', '--short', 'HEAD']) ||
  String(existing?.shortHash || '') ||
  'local';
const branch =
  String(process.env.BUILD_GIT_BRANCH || '').trim() ||
  safeExecFile('git', ['rev-parse', '--abbrev-ref', 'HEAD']) ||
  String(existing?.branch || '') ||
  'unknown';
const nowIso = String(process.env.BUILD_TIME_ISO || '').trim() || new Date().toISOString();
const datePart = nowIso.slice(0, 10).replace(/-/g, '');
const timePart = nowIso.slice(11, 19).replace(/:/g, '');
const envBuildVersion = String(process.env.BUILD_VERSION || '').trim();
const normalizeSemver = (value) => String(value || '').trim().replace(/^v/i, '').split('+')[0].trim();
const versionBase = normalizeSemver(pkg?.version || existing?.version || '0.0.0') || '0.0.0';
const version = normalizeSemver(envBuildVersion) || versionBase;
const buildMeta = envBuildVersion.includes('+')
  ? envBuildVersion.split('+').slice(1).join('+')
  : `${datePart}.${timePart}.${shortHash}`;
const versionInternal = `${version}+${buildMeta}`;
const buildId = `${versionInternal}-${datePart}.${timePart}-${shortHash}`;

const repositoryUrl = resolveGithubRepoUrl();
const commitsRaw = safeExecFile('git', ['log', '-n', '30', '--date=iso-strict', '--pretty=format:%H|%h|%cI|%an|%ae|%s']);
const commitsFromGit = commitsRaw
  ? commitsRaw
      .split('\n')
      .map((line) => line.trim())
      .filter(Boolean)
      .map((line) => {
        const [hash, short, dateIso, authorName, authorEmail, ...subjectParts] = line.split('|');
        return {
          hash: hash || '',
          shortHash: short || '',
          dateIso: dateIso || '',
          authorName: authorName || '',
          authorEmail: authorEmail || '',
          subject: subjectParts.join('|').trim() || '',
          commitUrl: repositoryUrl && hash ? `${repositoryUrl}/commit/${hash}` : '',
        };
      })
  : [];
const commits =
  parseEnvCommits() ||
  (commitsFromGit.length ? commitsFromGit : Array.isArray(existing?.commits) ? existing.commits : []);

const payload = {
  appName: 'Já no Caminho',
  version,
  versionLabel: `v${version.split('+')[0]}`,
  versionInternal,
  buildId,
  builtAt: nowIso,
  commitHash: commitHash || '',
  shortHash,
  branch,
  repositoryUrl,
  commits,
};

const content =
  `// Auto-generated by scripts/generate-build-info.mjs\n` +
  `// Do not edit manually.\n\n` +
  `export const APP_BUILD_INFO = ${JSON.stringify(payload, null, 2)} as const;\n\n` +
  `export type AppBuildInfo = typeof APP_BUILD_INFO;\n`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, content, 'utf8');

console.log(`[build-info] ${payload.versionLabel} ${payload.buildId}`);
