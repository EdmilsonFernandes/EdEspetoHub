import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const projectRoot = resolve(process.cwd());
const packageJsonPath = resolve(projectRoot, 'package.json');
const outputPath = resolve(projectRoot, 'src/generated/buildInfo.ts');

const safeExecFile = (bin, args) => {
  try {
    return execFileSync(bin, args, { cwd: projectRoot, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  } catch {
    return '';
  }
};

const pkg = JSON.parse(readFileSync(packageJsonPath, 'utf8'));
const version = String(pkg?.version || '0.0.0');
const commitHash = safeExecFile('git', ['rev-parse', 'HEAD']);
const shortHash = safeExecFile('git', ['rev-parse', '--short', 'HEAD']) || 'local';
const branch = safeExecFile('git', ['rev-parse', '--abbrev-ref', 'HEAD']) || 'unknown';
const now = new Date();
const nowIso = now.toISOString();
const datePart = nowIso.slice(0, 10).replace(/-/g, '');
const timePart = nowIso.slice(11, 19).replace(/:/g, '');
const buildId = `${version}-${datePart}.${timePart}-${shortHash}`;

const commitsRaw = safeExecFile('git', ['log', '-n', '30', '--date=iso-strict', '--pretty=format:%H|%h|%cI|%s']);
const commits = commitsRaw
  .split('\n')
  .map((line) => line.trim())
  .filter(Boolean)
  .map((line) => {
    const [hash, short, dateIso, ...subjectParts] = line.split('|');
    return {
      hash: hash || '',
      shortHash: short || '',
      dateIso: dateIso || '',
      subject: subjectParts.join('|').trim() || '',
    };
  });

const payload = {
  appName: 'Já no Caminho',
  version,
  versionLabel: `v${version}`,
  buildId,
  builtAt: nowIso,
  commitHash: commitHash || '',
  shortHash,
  branch,
  commits,
};

const content =
  `// Auto-generated by scripts/generate-build-info.mjs\n` +
  `// Do not edit manually.\n\n` +
  `export const APP_BUILD_INFO = ${JSON.stringify(payload, null, 2)} as const;\n\n` +
  `export type AppBuildInfo = typeof APP_BUILD_INFO;\n`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, content, 'utf8');

console.log(`[build-info] ${payload.versionLabel} ${payload.buildId}`);
